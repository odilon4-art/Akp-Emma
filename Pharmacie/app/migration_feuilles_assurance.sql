-- Ordonnance Mobile : extension feuilles d'assurance. À appliquer une seule fois dans Supabase SQL Editor.
-- Ne modifie ni ne supprime les tables existantes.
create table if not exists public.modeles_assurance (
 id bigint generated by default as identity primary key,
 assurance text not null check (assurance in ('Aucune assurance','AMU','Allianz','Ascoma','GTA','Gras Savoye','INAM','INAMI','NSIA','Saham/Sanlam','Sunu','TransVie')),
 nom text not null,
 description text,
 structure_json jsonb not null default '{}'::jsonb,
 photo_path text,
 statut text not null default 'en_attente' check (statut in ('en_attente','approuve','refuse')),
 cree_par uuid not null references auth.users(id),
 hopital_id bigint references public.hopitaux(id),
 approuve_par uuid references auth.users(id),
 approuve_le timestamptz,
 created_at timestamptz not null default now()
);
create table if not exists public.feuilles_assurance (
 id bigint generated by default as identity primary key,
 patient_id uuid not null references public.patients(id),
 hopital_id bigint references public.hopitaux(id),
 medecin_id uuid not null references auth.users(id),
 modele_id bigint references public.modeles_assurance(id),
 assurance text not null,
 numero_assure text,
 assure_nom text not null,
 assure_prenom text not null,
 assure_naissance date,
 assure_telephone text,
 donnees_medicales jsonb not null default '{}'::jsonb,
 statut text not null default 'brouillon' check (statut in ('brouillon','validee','annulee')),
 validee_par uuid references auth.users(id),
 validee_le timestamptz,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.delivrances_pharmacie (
 id bigint generated by default as identity primary key,
 feuille_id bigint not null references public.feuilles_assurance(id),
 pharmacie_id bigint references public.pharmacies(id),
 pharmacien_id uuid not null references auth.users(id),
 code_delivrance text not null,
 medicaments_delivres text not null,
 remarques text,
 created_at timestamptz not null default now(),
 unique(feuille_id, pharmacie_id)
);
create table if not exists public.journal_feuilles_assurance (
 id bigint generated by default as identity primary key,
 acteur_id uuid not null references auth.users(id),
 action text not null,
 table_cible text not null,
 id_cible text not null,
 details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create index if not exists feuilles_assurance_patient_idx on public.feuilles_assurance(patient_id, created_at desc);
create index if not exists feuilles_assurance_status_idx on public.feuilles_assurance(statut);
create index if not exists modeles_assurance_insurer_status_idx on public.modeles_assurance(assurance, statut);

alter table public.modeles_assurance enable row level security;
alter table public.feuilles_assurance enable row level security;
alter table public.delivrances_pharmacie enable row level security;
alter table public.journal_feuilles_assurance enable row level security;

do $$ begin
 create policy "modeles read approved or own or admin" on public.modeles_assurance for select to authenticated
 using (statut='approuve' or cree_par=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin')));
exception when duplicate_object then null; end $$;
do $$ begin
 create policy "hospital staff submit templates" on public.modeles_assurance for insert to authenticated
 with check (cree_par=auth.uid() and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('medecin','infirmier','admin','superadmin')));
exception when duplicate_object then null; end $$;
do $$ begin
 create policy "admin manages templates" on public.modeles_assurance for update to authenticated
 using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin')))
 with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin')));
exception when duplicate_object then null; end $$;

do $$ begin
 create policy "patient or care team reads sheets" on public.feuilles_assurance for select to authenticated using (
 exists(select 1 from public.patients pt where pt.id=patient_id and pt.user_id=auth.uid())
 or medecin_id=auth.uid()
 or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin'))
 or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('medecin','infirmier') and p.hopital_id=feuilles_assurance.hopital_id)
 or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='pharmacien')
 );
exception when duplicate_object then null; end $$;
do $$ begin
 create policy "doctor creates own draft sheets" on public.feuilles_assurance for insert to authenticated with check (
 medecin_id=auth.uid() and statut='brouillon' and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('medecin','infirmier') and (p.hopital_id is null or p.hopital_id=feuilles_assurance.hopital_id))
 );
exception when duplicate_object then null; end $$;
do $$ begin
 create policy "doctor validates own drafts" on public.feuilles_assurance for update to authenticated using (
 statut='brouillon' and (medecin_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin')))
 ) with check (statut in ('brouillon','validee','annulee') and (medecin_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin'))));
exception when duplicate_object then null; end $$;

do $$ begin
 create policy "pharmacy inserts separate dispensing record" on public.delivrances_pharmacie for insert to authenticated with check (
 pharmacien_id=auth.uid() and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='pharmacien' and (p.pharmacie_id is null or p.pharmacie_id=delivrances_pharmacie.pharmacie_id))
 and exists(select 1 from public.feuilles_assurance f where f.id=feuille_id and f.statut='validee')
 );
exception when duplicate_object then null; end $$;
do $$ begin
 create policy "patient pharmacy team reads dispensing" on public.delivrances_pharmacie for select to authenticated using (
 exists(select 1 from public.feuilles_assurance f join public.patients pt on pt.id=f.patient_id where f.id=feuille_id and pt.user_id=auth.uid())
 or pharmacien_id=auth.uid()
 or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin'))
 );
exception when duplicate_object then null; end $$;
do $$ begin
 create policy "actor reads audit entries" on public.journal_feuilles_assurance for select to authenticated using (acteur_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('admin','superadmin')));
exception when duplicate_object then null; end $$;
do $$ begin
 create policy "authenticated writes own audit entries" on public.journal_feuilles_assurance for insert to authenticated with check (acteur_id=auth.uid());
exception when duplicate_object then null; end $$;

